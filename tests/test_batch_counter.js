'use strict';
const assert = require('node:assert/strict');
const vm = require('node:vm');
const fs = require('node:fs');
const ContinuousCapture = require('../static/continuous.js');
const code = fs.readFileSync(require('node:path').join(__dirname, '../static/app.js'), 'utf8');
const elements = {};
const $ = id => elements[id] ||= {hidden:false, setAttribute(key, value) {this[key] = value;}};
const batch = new ContinuousCapture();
const ctx = { $, batch, mode:'train' };
vm.createContext(ctx);
vm.runInContext(code.slice(code.indexOf('function renderBatchCounter()'),code.indexOf('async function startContinuous()')),ctx);
ctx.renderBatchCounter(); assert($('batch-counter').hidden);
const serial=batch.start(60);
ctx.renderBatchCounter(); assert.equal($('batch-counter').textContent,'0/60'); assert($('camera-state').hidden);
for(let n=1;n<=30;n++)batch.complete(`draft-${n}`,serial);
batch.complete('draft-30',serial);
ctx.renderBatchCounter(); assert.equal($('batch-counter').textContent,'30/60');
batch.stop();ctx.renderBatchCounter();assert.equal($('batch-counter').textContent,'30/60');
ctx.mode='test';ctx.renderBatchCounter();assert($('batch-counter').hidden);assert(!$('camera-state').hidden);
ctx.mode='train';batch.start(5);ctx.renderBatchCounter();assert.equal($('batch-counter').textContent,'0/5');
assert.equal($('batch-counter')['aria-label'],'0 de 5 tomas completas');
console.log('Contador: inicio, avance, duplicados, parada, cambio de vista y nueva tanda correctos.');
